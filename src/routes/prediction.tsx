import { createFileRoute } from "@tanstack/react-router";
import { Area, ComposedChart, Line, ReferenceLine, ResponsiveContainer, Tooltip, XAxis, YAxis } from "recharts";
import { Info } from "lucide-react";
import { data, fmtTime, THRESHOLDS } from "@/lib/floodguard/data";
import { chartTooltip, DemoTag, PageHeader, Panel, RiskBadge } from "@/components/floodguard/ui";

export const Route = createFileRoute("/prediction")({
  head: () => ({ meta: [
    { title: "Flood Prediction — FloodGuard" },
    { name: "description", content: "48-hour predicted water level, risk probability and explanation (simulated demo forecast)." },
    { property: "og:title", content: "FloodGuard Flood Prediction" },
    { property: "og:description", content: "Forecast water levels and flood risk probability." },
  ] }),
  component: Prediction,
});

function Prediction() {
  const f = data.forecast();
  const pts = f.points.map((p) => ({ ...p, t: `+${Math.round((new Date(p.time).getTime() - new Date(f.points[0]!.time).getTime()) / 3600000)}h`, band: [p.low, p.high] }));
  const peakAt = f.points.find((p) => p.predicted === f.peak)!;
  return (
    <>
      <PageHeader title="Flood prediction" subtitle={`Model: ${f.model}`} />
      <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
        {[
          ["Predicted peak", `${f.peak.toFixed(2)} m`, fmtTime(peakAt.time)],
          ["Forecast horizon", `${f.horizonHours} h`, "Hourly resolution"],
          ["Flood probability", `${f.probability}%`, `Exceeding ${THRESHOLDS.high} m`],
        ].map(([l, v, s]) => (
          <div key={l} className="rounded-xl border border-border bg-card p-5">
            <div className="flex items-center justify-between"><span className="text-xs uppercase tracking-wide text-muted-foreground">{l}</span><DemoTag /></div>
            <p className="mt-3 font-display text-3xl font-semibold">{v}</p><p className="mt-1 text-xs text-muted-foreground">{s}</p>
          </div>
        ))}
        <div className="rounded-xl border border-border bg-card p-5">
          <span className="text-xs uppercase tracking-wide text-muted-foreground">Forecast risk</span>
          <div className="mt-3"><RiskBadge risk={f.risk} className="text-base" /></div>
          <div className="mt-3 h-2 overflow-hidden rounded-full bg-muted"><div className="h-full bg-water" style={{ width: `${f.probability}%` }} /></div>
        </div>
      </div>
      <Panel title="Predicted water level with uncertainty" className="mt-6">
        <div className="h-80"><ResponsiveContainer><ComposedChart data={pts}>
          <XAxis dataKey="t" stroke="var(--muted-foreground)" fontSize={11} interval={5} />
          <YAxis stroke="var(--muted-foreground)" fontSize={11} unit=" m" width={50} domain={[2, 4]} />
          <Tooltip {...chartTooltip} />
          <Area dataKey="band" name="Uncertainty" stroke="none" fill="var(--chart-1)" fillOpacity={0.15} />
          <ReferenceLine y={THRESHOLDS.severe} stroke="var(--destructive)" strokeDasharray="4 4" label={{ value: "Severe", fill: "var(--destructive)", fontSize: 11 }} />
          <ReferenceLine y={THRESHOLDS.high} stroke="var(--warning)" strokeDasharray="4 4" label={{ value: "High", fill: "var(--warning)", fontSize: 11 }} />
          <Line dataKey="predicted" name="Predicted (m)" stroke="var(--chart-1)" strokeWidth={2.5} dot={false} />
        </ComposedChart></ResponsiveContainer></div>
      </Panel>
      <div className="mt-6 grid gap-6 lg:grid-cols-2">
        <Panel title="Why this prediction?">
          <p className="mb-4 text-sm text-muted-foreground">Rainfall upstream over the past 72 hours and a steady rising trend suggest the level may reach the high-risk threshold within ~24 hours, then slowly recede.</p>
          <div className="space-y-3">
            {f.factors.map((x) => (
              <div key={x.label}><div className="mb-1 flex justify-between text-sm"><span>{x.label}</span><span className="font-mono text-muted-foreground">{x.weight}%</span></div>
                <div className="h-1.5 rounded-full bg-muted"><div className="h-full rounded-full bg-primary" style={{ width: `${x.weight}%` }} /></div></div>
            ))}
          </div>
        </Panel>
        <Panel title="About this forecast" action={<Info className="size-4 text-muted-foreground" />}>
          <ul className="space-y-2 text-sm text-muted-foreground">
            <li>• This is a <strong className="text-warning">simulated demo forecast</strong>, generated by a placeholder heuristic — not a real prediction.</li>
            <li>• The platform is designed to plug in a trained ML model (e.g. LSTM / gradient boosting) through a single data interface.</li>
            <li>• Uncertainty widens with lead time; confidence bands will come from the model once connected.</li>
            <li>• Always follow official guidance from local authorities.</li>
          </ul>
        </Panel>
      </div>
    </>
  );
}
